# ------------------------------------------------------------
# 1. Creating a Dictionary
# ------------------------------------------------------------

dict_1 = {
    101: "Devendra",
    102: "MD",
    103: "Vandana"
}

print(dict_1)


# ------------------------------------------------------------
# 2. Adding a New Key-Value Pair
# ------------------------------------------------------------

dict_1[4] = "Prachi"

print(dict_1)


# ------------------------------------------------------------
# 3. Accessing a Value Using a Key
# ------------------------------------------------------------

print(dict_1[101])


# ------------------------------------------------------------
# 4. pop() - Removing a Key-Value Pair
# ------------------------------------------------------------

removed_value = dict_1.pop(101)

print("Removed value:", removed_value)
print(dict_1)


# ------------------------------------------------------------
# 5. del - Removing a Key-Value Pair
# ------------------------------------------------------------

del dict_1[102]

print(dict_1)


# ------------------------------------------------------------
# 6. clear() - Removing All Items
# ------------------------------------------------------------

dict_1.clear()

print(dict_1)


# ------------------------------------------------------------
# 7. del - Deleting the Entire Dictionary
# ------------------------------------------------------------

del dict_1

# If you try to print dict_1 now, it will give:
# NameError: name 'dict_1' is not defined


# ------------------------------------------------------------
# 8. Creating a New Dictionary
# ------------------------------------------------------------

dict_1 = {
    "name": "Devendra Rathore",
    "age": 18,
    "course": "BCA"
}

print(dict_1)


# ------------------------------------------------------------
# 9. Accessing a Value
# ------------------------------------------------------------

print(dict_1["name"])


# ------------------------------------------------------------
# 10. get() Method
# ------------------------------------------------------------

print(dict_1.get("height"))

# get() returns None if the key does not exist.


# ------------------------------------------------------------
# 11. Adding a New Key-Value Pair
# ------------------------------------------------------------

dict_1["height"] = 5.10

print(dict_1)


# ------------------------------------------------------------
# 12. copy() Method
# ------------------------------------------------------------

dict_2 = dict_1.copy()

print(dict_2)


# ------------------------------------------------------------
# 13. keys() Method
# ------------------------------------------------------------

print(dict_1.keys())


# ------------------------------------------------------------
# 14. values() Method
# ------------------------------------------------------------

print(dict_1.values())


# ------------------------------------------------------------
# 15. Loop Through Dictionary Keys
# ------------------------------------------------------------

for k in dict_1:
    print(k)


# ------------------------------------------------------------
# 16. Loop Through Dictionary Values
# ------------------------------------------------------------

for k in dict_1:
    print(dict_1[k])


# ------------------------------------------------------------
# 17. Print Key and Value Together
# ------------------------------------------------------------

for k in dict_1:
    print(k, dict_1[k])


# ------------------------------------------------------------
# 18. Print Key and Value with :
# ------------------------------------------------------------

for k in dict_1:
    print(k, ":", dict_1[k])


# ------------------------------------------------------------
# 19. Checking Whether a Key Exists
# ------------------------------------------------------------

if "name" in dict_1:
    print(f"Yes name is present: {dict_1['name']}")
else:
    print("Not Present")


# ------------------------------------------------------------
# 20. Dictionary Comprehension
# ------------------------------------------------------------

cubes = {
    x: x * x * x
    for x in range(1, 11)
}

print(cubes)


# ------------------------------------------------------------
# 21. Dictionary Containing Lists of Tuples
# ------------------------------------------------------------

data = {
    101: [
        ("Name", "Devendra Rathore"),
        ("Age", 18),
        ("Course", "BCA")
    ]
}

print(data)


# ------------------------------------------------------------
# 22. len() - Number of Key-Value Pairs
# ------------------------------------------------------------

print(len(dict_1))


# ------------------------------------------------------------
# 23. str() - Convert Dictionary to String
# ------------------------------------------------------------

print(str(dict_1))


# ------------------------------------------------------------
# 24. Nested Dictionary
# ------------------------------------------------------------

data = {
    101: {
        "name": "Devendra Rathore",
        "age": 18,
        "course": "BCA"
    },

    102: {
        "name": "MD",
        "age": 19,
        "course": "B.Tech"
    }
}

print(data)


# ------------------------------------------------------------
# 25. Accessing One Dictionary Inside Another Dictionary
# ------------------------------------------------------------

print(data[101])


# ------------------------------------------------------------
# 26. Accessing Specific Value from Nested Dictionary
# ------------------------------------------------------------

print(data[101]["name"])
print(data[101]["age"])
print(data[101]["course"])


# ------------------------------------------------------------
# 27. Printing Keys of Nested Dictionary
# ------------------------------------------------------------

print(data.keys())


# ------------------------------------------------------------
# 28. Printing Values of Nested Dictionary
# ------------------------------------------------------------

print(data.values())


# ------------------------------------------------------------
# 29. Loop Through Nested Dictionary
# ------------------------------------------------------------

for student_id in data:
    print(student_id)
    print(data[student_id])


# ------------------------------------------------------------
# 30. Loop Through Nested Dictionary and Print Details
# ------------------------------------------------------------

for student_id in data:
    print("Student ID:", student_id)
    print("Name:", data[student_id]["name"])
    print("Age:", data[student_id]["age"])
    print("Course:", data[student_id]["course"])
    print()