#    Write A Program To Convert Celsius To Fahrenheit (Date:27/08/2026)

# Taking Celsius As Input From The User

C = float(input("Enter the temperature in celsius: "))

# Converting The Temperature Celsius To Fahrenheit 

F = (C * 9/5) + 32

# Printing the necessary statements

print("-----Celsius To Fahrenheit-----")
print(C,"\u00B0C is equal to", F,"\u00B0F")












